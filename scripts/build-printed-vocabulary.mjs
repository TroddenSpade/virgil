#!/usr/bin/env node
/**
 * Extract the vocabulary printed in the six books that carry it.
 *
 * The wordlist needs these entries for every learned chapter, but importing
 * six full books into the wordlist chunk would pull megabytes of readings and
 * grammar along with them. This compact index keeps only the printed words.
 *
 * Output: src/data/printed-vocabulary.generated.js
 *
 * Run with: node scripts/build-printed-vocabulary.mjs
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { books } from './book-data.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const VOCABULARY_BOOK_IDS = new Set([
  'familia-romana',
  'roma-aeterna',
  'exercitia-latina',
  'latin-via-ovid',
  'companion-to-familia-romana',
  'companion-to-roma-aeterna',
])

const printed = {}
let entries = 0

for (const book of books) {
  if (!VOCABULARY_BOOK_IDS.has(book.id)) continue
  for (const chapter of book.chapters) {
    if (!chapter.vocabulary?.length) continue
    printed[`${book.id}:${chapter.number}`] = chapter.vocabulary.map((entry) => {
      const row = {}
      if (entry.latin != null) row.latin = entry.latin
      if (entry.english != null) row.english = entry.english
      if (entry.pos != null) row.pos = entry.pos
      if (entry.group != null) row.group = entry.group
      return row
    })
    entries += chapter.vocabulary.length
  }
}

const output = `// Generated by scripts/build-printed-vocabulary.mjs — do not edit by hand.
// Printed vocabulary for the six books that carry it, keyed by book id and
// chapter number. Readings and grammar are not included.
export const printedVocabulary = ${JSON.stringify(printed)}
`

await writeFile(join(ROOT, 'src/data/printed-vocabulary.generated.js'), output, 'utf8')

console.log(
  `Wrote src/data/printed-vocabulary.generated.js — ${Object.keys(printed).length} chapters, ${entries} words, ${Buffer.byteLength(output)} bytes`,
)
