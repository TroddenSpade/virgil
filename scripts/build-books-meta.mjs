#!/usr/bin/env node
/**
 * Build the small, eagerly loaded book registry.
 *
 * The app needs titles, shelf metadata, counts and a chapter outline on almost
 * every page, but it must not import the full text of all 43 books to show a
 * library card. This script reads each book module once, keeps only the light
 * fields, and writes src/data/books-meta.generated.js.
 *
 * Full chapter text is loaded on demand by src/data/book-loader.js.
 *
 * Run with: node scripts/build-books-meta.mjs
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { BOOK_MODULES } from './book-modules.mjs'
import { sources } from '../src/data/sources.generated.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// The books whose chapters can also be read in a full-text reference edition.
const SOURCE_BY_SLUG = {
  'familia-romana': 'familia-romana',
  'companion-to-familia-romana': 'companion',
  'latin-via-ovid': 'latin-via-ovid',
  'exercitia-latina': 'exercitia',
}

const sourceBySlug = Object.fromEntries(sources.map((source) => [source.slug, source]))

function referenceIdFor(sourceSlug, number) {
  if (!sourceSlug) return null
  return sourceBySlug[sourceSlug]?.chapters.find((chapter) => chapter.number === number)?.id || null
}

function outlineChapter(chapter, sourceSlug) {
  return {
    number: chapter.number,
    roman: chapter.roman,
    slug: chapter.slug,
    title: chapter.title || null,
    latinTitle: chapter.latinTitle || null,
    complete: Boolean(chapter.complete),
    referenceId: referenceIdFor(sourceSlug, chapter.number),
  }
}

function outlineExtra(extra) {
  return {
    id: extra.id,
    slug: extra.slug,
    title: extra.title,
    latinTitle: extra.latinTitle || null,
  }
}

const books = []

for (const moduleName of BOOK_MODULES) {
  const mod = await import(`../src/data/${moduleName}/index.js`)
  const bookExtras = mod.book.extras || mod.extras || []
  const { chapters: _chapters, extras: _extras, ...book } = mod.book
  const sourceSlug = SOURCE_BY_SLUG[book.slug] || null
  const chapters = mod.chapters || []

  books.push({
    ...book,
    modulePath: `./${moduleName}/index.js`,
    ...(sourceSlug ? { sourceSlug } : {}),
    chapterCount: book.chapterCount ?? chapters.length,
    readyCount:
      book.readyCount ?? chapters.filter((chapter) => chapter.complete).length,
    readingCount:
      book.readingCount ??
      chapters.reduce((total, chapter) => total + (chapter.readings?.length || 0), 0),
    chapters: chapters.map((chapter) => outlineChapter(chapter, sourceSlug)),
    extras: bookExtras.map(outlineExtra),
  })
}

const output = `// Generated by scripts/build-books-meta.mjs — do not edit by hand.
// The light book registry: titles, shelf data, counts and chapter outlines.
// Full chapter text lives in the per-book chunks loaded by book-loader.js.
export const booksMeta = ${JSON.stringify(books)}
`

await writeFile(join(ROOT, 'src/data/books-meta.generated.js'), output, 'utf8')

const chapterCount = books.reduce((total, book) => total + book.chapters.length, 0)
console.log(
  `Wrote src/data/books-meta.generated.js — ${books.length} books, ${chapterCount} chapter outlines, ${Buffer.byteLength(output)} bytes`,
)
